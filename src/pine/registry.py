"""The verification registry (PINE_PLAN.md §11 H2): what has been checked against what.

``verification.yaml`` (shipped with the package) records, per built-in and per probe group,
which TradingView exports confirmed it, plus each built-in's input-rounding bound and
deliberate-bug tests. Status is derived, never typed in: an entry is *verified* when at least
one export confirmed it. `problems` cross-checks the file against the code;
``tests/test_registry.py`` fails on any problem, so the registry cannot drift from the code.

Command line::

    python -m pine.registry                   # print the README status section
    python -m pine.registry --check README.md # exit 1 if README's section is out of date
    python -m pine.registry --write README.md # regenerate README's section
"""

from __future__ import annotations

import argparse
import inspect
import sys
from functools import cache
from importlib import resources
from pathlib import Path
from typing import Any

import yaml

__all__ = ["load", "problems", "status", "markdown", "main", "START", "END"]

SCHEMA = 1
START = "<!-- verification-table:start (generated by python -m pine.registry) -->"
END = "<!-- verification-table:end -->"
ROOT = Path(__file__).resolve().parents[2]  # repository root in a checkout


@cache
def load() -> dict[str, Any]:
    text = resources.files("pine").joinpath("verification.yaml").read_text(encoding="utf-8")
    data = yaml.safe_load(text)
    if not isinstance(data, dict) or data.get("schema") != SCHEMA:
        raise ValueError(f"verification.yaml: expected a mapping with schema {SCHEMA}")
    return data


def status(entry: dict[str, Any], capture: str | None = None) -> str:
    """``verified`` (an export confirmed it), ``capture ready`` (a capture script covers it,
    no export yet), or ``unverified``."""
    if entry.get("tradingview"):
        return "verified"
    if capture or entry.get("capture"):
        return "capture ready"
    return "unverified"


def _public_ta() -> set[str]:
    from pine import ta

    return {n for n in ta.__all__ if callable(getattr(ta, n)) and not n.isupper()} - {"NaPolicy"}


def _runtime_methods() -> set[str]:
    from pine.runtime import _TA

    return {n for n, _ in inspect.getmembers(_TA, inspect.isfunction) if not n.startswith("_")}


def _expected_by_group() -> dict[str, str]:
    from pine import builtin_capture, semantics, strategy_capture

    out = {f"semantics.{g}": h for g, h in semantics.EXPECTED.items()}
    out |= {f"builtins.{g}": h for g, h in builtin_capture.EXPECTED.items()}
    out |= {f"strategy.{g}": h for g, h in strategy_capture.EXPECTED_HYP.items()}
    return out


def _bound_exists(ref: str) -> bool:
    from pine import sensitivity

    if ref.startswith("LIPSCHITZ:"):
        return ref.split(":", 1)[1] in sensitivity.LIPSCHITZ
    return callable(getattr(sensitivity, ref, None))


def problems(data: dict[str, Any] | None = None, root: Path = ROOT) -> list[str]:
    """Every way the registry disagrees with the code (empty: consistent). ``root`` is the
    repository checkout, for the mutation-test paths (skipped if absent, e.g. installed)."""
    data = load() if data is None else data
    out: list[str] = []
    exports = data.get("exports", {})
    builtins = data.get("builtins", {})
    decisions = data.get("decisions", {})
    used: set[str] = set()

    def refs(where: str, ids) -> None:
        for e in ids or []:
            used.add(e)
            if e not in exports:
                out.append(f"{where}: unknown export {e!r}")

    public = _public_ta()
    for name in sorted(public - set(builtins)):
        out.append(f"builtins: pine.ta.{name} has no entry")
    for name in sorted(set(builtins) - public):
        out.append(f"builtins: {name!r} is not a public pine.ta function")
    mapped = {b.get("runtime") for b in builtins.values()} - {None}
    for m in sorted(_runtime_methods() - mapped):
        out.append(f"builtins: runtime ctx.ta.{m} is not mapped by any entry")
    for m in sorted(mapped - _runtime_methods()):
        out.append(f"builtins: runtime ctx.ta.{m} does not exist")
    have_tests = (root / "tests").is_dir()
    for name, b in builtins.items():
        where = f"builtins.{name}"
        refs(where, b.get("tradingview"))
        refs(f"{where}.na_policy", b.get("na_policy"))
        if b.get("capture") not in (None, "reference", "semantics", "builtins"):
            out.append(f"{where}: unknown capture {b.get('capture')!r}")
        if b.get("bound") is not None and not _bound_exists(b["bound"]):
            out.append(f"{where}: bound {b['bound']!r} not found in pine.sensitivity")
        if b.get("bound") is None and b.get("pine") and not b.get("notes"):
            out.append(f"{where}: no bound and no note saying why")
        mut = b.get("mutation")
        if mut and have_tests:
            p = root / mut
            if not p.is_file():
                out.append(f"{where}: mutation file {mut} missing")
            elif f"ta.{name}" not in p.read_text(encoding="utf-8"):
                out.append(f"{where}: {mut} never calls ta.{name}")
        if set(b.get("na_policy") or []) - set(b.get("tradingview") or []):
            out.append(f"{where}: na policy decided on an export that did not verify it")
    expected = _expected_by_group()
    for g in sorted(set(expected) - set(decisions)):
        out.append(f"decisions: probe group {g} has no entry")
    for g in sorted(set(decisions) - set(expected)):
        out.append(f"decisions: {g} is not a probe group")
    for g, d in decisions.items():
        refs(f"decisions.{g}", d.get("tradingview"))
        if g in expected and d.get("expected") != expected[g]:
            out.append(
                f"decisions.{g}: registry says {d.get('expected')!r}, code implements "
                f"{expected[g]!r}"
            )
    for e in sorted(set(exports) - used):
        out.append(f"exports: {e} is not referenced")
    return out


def _cell(ids) -> str:
    return ", ".join(ids) if ids else "—"


def markdown(data: dict[str, Any] | None = None) -> str:
    """The README status section (between `START` and `END`)."""
    data = load() if data is None else data
    ex = data["exports"]
    lines = [
        START,
        "",
        "Generated from [`src/pine/verification.yaml`](src/pine/verification.yaml); "
        "**verified** means at least one TradingView export confirmed it.",
        "",
        "Exports: "
        + "; ".join(
            f"`{k}` {v['symbol']} {v['timeframe']} (from bar {v['first_bar']})"
            for k, v in ex.items()
        )
        + ".",
        "",
        "| built-in | runtime | status | TradingView exports | rounding bound | bug tests |",
        "|---|---|---|---|---|---|",
    ]
    for b in data["builtins"].values():
        if not b.get("pine"):
            continue
        lines.append(
            f"| `{b['pine']}` | {'yes' if b.get('runtime') else '—'} | {status(b)} "
            f"| {_cell(b.get('tradingview'))} | {'yes' if b.get('bound') else 'none'} "
            f"| {'yes' if b.get('mutation') else '—'} |"
        )
    groups: dict[str, list[str]] = {}
    for g, d in data["decisions"].items():
        groups.setdefault(g.split(".", 1)[0], []).append(status(d, capture="yes"))
    lines += ["", "| execution rules | verified | capture ready |", "|---|---|---|"]
    for area, sts in groups.items():
        lines.append(
            f"| {area} | {sts.count('verified')} of {len(sts)} | {sts.count('capture ready')} |"
        )
    pending = [g for g, d in data["decisions"].items() if not d.get("tradingview")]
    lines += ["", f"Awaiting an export: {', '.join(f'`{g}`' for g in pending)}.", "", END]
    return "\n".join(lines)


def _splice(text: str, section: str) -> str:
    if START not in text or END not in text:
        raise ValueError(f"markers not found; add {START!r} and {END!r}")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + section + tail


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m pine.registry", description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", metavar="FILE", help="exit 1 if FILE's section is out of date")
    g.add_argument("--write", metavar="FILE", help="regenerate FILE's section")
    args = ap.parse_args(argv)
    errs = problems()
    if errs:
        print(
            "verification.yaml is inconsistent with the code:", *errs, sep="\n  ", file=sys.stderr
        )
        return 2
    section = markdown()
    if not (args.check or args.write):
        print(section)
        return 0
    path = Path(args.check or args.write)
    try:
        text = path.read_text(encoding="utf-8")
        new = _splice(text, section)
    except (OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    if args.write:
        path.write_text(new, encoding="utf-8")
        return 0
    if new != text:
        print(f"{path} is out of date: run python -m pine.registry --write {path}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
